package waf

import (
	"net/http"
	"testing"

	"solitools/internal/httpx"
)

func response(status int, headers map[string]string, body string) *httpx.Response {
	header := make(http.Header, len(headers))
	for name, value := range headers {
		header.Set(name, value)
	}
	return &httpx.Response{URL: "https://target.test/", Status: status, Header: header, Body: []byte(body)}
}

func TestDetectProviders(t *testing.T) {
	cases := []struct {
		name      string
		response  *httpx.Response
		want      Provider
		wantBlock bool
	}{
		{
			name:      "cloudflare header on a normal page",
			response:  response(200, map[string]string{"CF-Ray": "8a1b2c3d-LHR", "Server": "cloudflare"}, "<html><body>app</body></html>"),
			want:      ProviderCloudflare,
			wantBlock: false, // present, but this is the application
		},
		{
			name:      "cloudflare challenge",
			response:  response(403, map[string]string{"cf-ray": "8a1b2c3d-LHR"}, "<html><title>Attention Required! | Cloudflare</title></html>"),
			want:      ProviderCloudflare,
			wantBlock: true,
		},
		{
			name:      "cloudflare browser verification on 200",
			response:  response(200, nil, "<html><body>Just a moment...</body></html>"),
			want:      ProviderCloudflare,
			wantBlock: true,
		},
		{
			name:      "cloudfront block",
			response:  response(403, map[string]string{"X-Amz-Cf-Id": "abc"}, "The request could not be satisfied."),
			want:      ProviderCloudFront,
			wantBlock: true,
		},
		{
			name:      "cloudfront body signature",
			response:  response(200, nil, "<html>Generated by cloudfront</html>"),
			want:      ProviderCloudFront,
			wantBlock: true,
		},
		{
			name:      "akamai server",
			response:  response(403, map[string]string{"Server": "AkamaiGHost"}, "Access Denied"),
			want:      ProviderAkamai,
			wantBlock: true,
		},
		{
			name:      "akamai reference number",
			response:  response(403, nil, "Access Denied. Reference #18.abcd1234"),
			want:      ProviderAkamai,
			wantBlock: true,
		},
		{
			name:      "imperva header",
			response:  response(403, map[string]string{"X-Iinfo": "9-12345"}, "Request unsuccessful."),
			want:      ProviderImperva,
			wantBlock: true,
		},
		{
			name:      "imperva resource on 200",
			response:  response(200, nil, "<script src=\"/_Incapsula_Resource\"></script>"),
			want:      ProviderImperva,
			wantBlock: true,
		},
		{
			name:      "modsecurity block page",
			response:  response(403, nil, "This error was generated by Mod_Security."),
			want:      ProviderModSecurity,
			wantBlock: true,
		},
		{
			name:      "generic rate limit",
			response:  response(429, nil, ""),
			want:      ProviderGenericBlock,
			wantBlock: true,
		},
		{
			name:      "generic empty 403",
			response:  response(403, nil, "   "),
			want:      ProviderGenericBlock,
			wantBlock: true,
		},
		{
			name:      "generic block wording",
			response:  response(403, nil, "<h1>Request blocked</h1>"),
			want:      ProviderGenericBlock,
			wantBlock: true,
		},
		{
			name:      "application 403 is left alone",
			response:  response(403, nil, "<html><body><form action=\"/login\"><input name=\"u\"></form></body></html>"),
			want:      "",
			wantBlock: false,
		},
		{
			name:      "ordinary page",
			response:  response(200, map[string]string{"Server": "nginx"}, "<html><body>hello</body></html>"),
			want:      "",
			wantBlock: false,
		},
	}

	for _, testCase := range cases {
		t.Run(testCase.name, func(t *testing.T) {
			provider, ok := Detect(testCase.response)
			if testCase.want == "" {
				if ok {
					t.Fatalf("Detect = %q, want no provider", provider)
				}
			} else if !ok || provider != testCase.want {
				t.Fatalf("Detect = %q,%v, want %q", provider, ok, testCase.want)
			}
			if got := IsBlockPage(testCase.response); got != testCase.wantBlock {
				t.Fatalf("IsBlockPage = %v, want %v", got, testCase.wantBlock)
			}
		})
	}
}

func TestDetectNilResponse(t *testing.T) {
	if provider, ok := Detect(nil); ok || provider != "" {
		t.Fatal("a nil response has no provider")
	}
	if IsBlockPage(nil) {
		t.Fatal("a nil response is not a block page")
	}
}

func TestDetectReadsEveryServerHeader(t *testing.T) {
	header := make(http.Header)
	header.Add("Server", "BaseHTTP/0.6 Python/3.13")
	header.Add("Server", "cloudflare")

	provider, ok := Detect(&httpx.Response{Status: 200, Header: header, Body: []byte("app")})
	if !ok || provider != ProviderCloudflare {
		t.Fatalf("Detect = %q,%v; a duplicate Server header must still be read", provider, ok)
	}
}

func TestGenericBlockNeedsSyntheticEvidence(t *testing.T) {
	// A 403 that merely says Forbidden is what plenty of real apps return for a
	// valid page; treating it as a WAF page would hide findings.
	if _, ok := Detect(response(403, nil, "<h1>Forbidden</h1>")); ok {
		t.Fatal("a plain Forbidden page must not be classified as a WAF block")
	}
}
