// Package waf recognises web application firewalls and the synthetic pages
// they return instead of application output.
//
// The distinction that matters for accuracy is not "is a WAF present?" but
// "is this response the application or the WAF?". A Cloudflare-fronted site
// answers normally all day and still sends the same `cf-ray` header; only a
// challenge or block page may hide a finding. Detect answers the first
// question, IsBlockPage the second.
//
// Everything here is pure classification over a response already in memory: no
// extra requests, no external dependencies.
package waf

import (
	"strings"

	"github.com/soliofski/SoliTools/internal/httpx"
)

// Provider names a known product. The zero value means "none detected".
type Provider string

const (
	// ProviderCloudflare is Cloudflare's edge, including its challenge pages.
	ProviderCloudflare Provider = "Cloudflare"
	// ProviderCloudFront is CloudFront / AWS WAF.
	ProviderCloudFront Provider = "CloudFront / AWS WAF"
	// ProviderAkamai is Akamai's edge (AkamaiGHost).
	ProviderAkamai Provider = "Akamai"
	// ProviderImperva is Imperva / Incapsula.
	ProviderImperva Provider = "Imperva / Incapsula"
	// ProviderModSecurity is ModSecurity with the stock block page.
	ProviderModSecurity Provider = "ModSecurity"
	// ProviderGenericBlock is a 429, or a synthetic 403 with no application
	// context, that no vendor signature explains.
	ProviderGenericBlock Provider = "Generic Block"
)

// bodySample bounds how much of a response is scanned for signatures. Block
// pages are small; scanning megabytes of an application page buys nothing.
const bodySample = 64 << 10

// Detect reports which known WAF fronts this response. It is a presence check:
// a normal 200 from a Cloudflare-fronted site returns Cloudflare,true, while
// IsBlockPage stays false for it.
func Detect(response *httpx.Response) (Provider, bool) {
	if response == nil {
		return "", false
	}
	body := sample(response)
	header := func(name string) string {
		return strings.ToLower(strings.TrimSpace(response.Header.Get(name)))
	}
	// Proxies and test servers can emit more than one Server header; Get would
	// only see the first, so join every value before matching.
	server := strings.ToLower(strings.Join(response.Header.Values("Server"), " "))

	if header("cf-ray") != "" || header("cf-cache-status") != "" ||
		strings.Contains(server, "cloudflare") ||
		containsAny(body,
			"attention required! | cloudflare",
			"just a moment...",
			"error code: 1020",
			"cf-browser-verification") {
		return ProviderCloudflare, true
	}

	if header("x-amz-cf-id") != "" || header("x-amzn-errortype") != "" ||
		containsAny(body,
			"the request could not be satisfied",
			"generated by cloudfront") {
		return ProviderCloudFront, true
	}

	if strings.Contains(server, "akamaighost") || header("x-akamai-transformed") != "" ||
		containsAny(body, "reference #") {
		return ProviderAkamai, true
	}

	if header("x-iinfo") != "" || strings.Contains(header("x-cdn"), "incapsula") ||
		containsAny(body,
			"_incapsula_resource",
			"incident id:") {
		return ProviderImperva, true
	}

	if strings.Contains(server, "mod_security") ||
		containsAny(body,
			"this error was generated by mod_security",
			"mod_security") {
		return ProviderModSecurity, true
	}

	if response.Status == 429 {
		return ProviderGenericBlock, true
	}
	// A 403 with an empty body, or one carrying known block wording, is a
	// synthetic answer. A 403 with real application markup (a form, a link,
	// a script) is left alone: over-suppressing hides genuine findings.
	if response.Status == 403 && (strings.TrimSpace(body) == "" || containsAny(body, genericBlockMarkers...)) {
		return ProviderGenericBlock, true
	}
	return "", false
}

// IsBlockPage reports whether this response is a synthetic interception rather
// than application output.
func IsBlockPage(response *httpx.Response) bool {
	if response == nil {
		return false
	}
	provider, ok := Detect(response)
	if !ok {
		return false
	}
	switch response.Status {
	case 403, 406, 429, 503:
		return true
	}
	// Some vendors serve a challenge with a 200 and a body signature.
	return provider != ProviderGenericBlock && hasChallengeBody(response)
}

// genericBlockMarkers are phrasings that make a 403 synthetic without a vendor
// header. Deliberately specific: plain "Access Denied" is also what a normal
// application authorises page says.
var genericBlockMarkers = []string{
	"request blocked",
	"request unsuccessful",
	"web application firewall",
	"incident id:",
}

func hasChallengeBody(response *httpx.Response) bool {
	body := sample(response)
	return containsAny(body,
		"attention required! | cloudflare",
		"just a moment...",
		"error code: 1020",
		"cf-browser-verification",
		"the request could not be satisfied",
		"generated by cloudfront",
		"reference #",
		"_incapsula_resource",
		"this error was generated by mod_security")
}

func sample(response *httpx.Response) string {
	body := response.Body
	if len(body) > bodySample {
		body = body[:bodySample]
	}
	return strings.ToLower(string(body))
}

func containsAny(body string, markers ...string) bool {
	for _, marker := range markers {
		if strings.Contains(body, marker) {
			return true
		}
	}
	return false
}
